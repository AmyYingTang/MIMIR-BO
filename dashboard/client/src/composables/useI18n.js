export function useI18n() {
  const t = computed(() => messages[currentLang.value])
  const lang = computed({
    get: () => currentLang.value,
    set: (v) => { currentLang.value = v },
  })

  function timeAgo(dateStr) {
    if (!dateStr) return t.value.unknown
    const diff = Date.now() - new Date(dateStr).getTime()
    const mins = Math.floor(diff / 60000)
    if (mins < 1) return t.value.justNow
    if (mins < 60) return t.value.minsAgo(mins)
    const h = Math.floor(mins / 60)
    if (h < 24) return t.value.hoursAgo(h)
    const d = Math.floor(h / 24)
    if (d < 7) return t.value.daysAgo(d)
    return t.value.weeksAgo(Math.floor(d / 7))
  }

  return { t, lang, timeAgo }
}
